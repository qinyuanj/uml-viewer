-- IR orchestration is pure: IO capabilities are passed to read_policy/generate.
local E=require('uml.edn')
local G=require('uml.graph')
local P=require('uml.domain.policy')
local Detection=require('uml.domain.language_detection')
local M={}
local K,V=E.keyword,E.vector
local function get(m,k,d) local v=E.get(m,K(k)); if v==nil or v==E.nil_value or v==false then return d end; return v end
local function options(prefix) return E.map{{K('prefix'),prefix}} end
local function invoke(impl,root,opts) if type(impl)=='function' then return impl(root,opts) end; return impl:scan(root,opts) end
function M.read_policy(path,io_adapter) local p=E.parse(io_adapter.read(path)); assert(E.kind(p)=='map','policy must be an EDN map'); return p end
local function canonical(value)
  local kind=E.kind(value)
  if kind=='map' then
    local entries={}
    for _,entry in ipairs(value) do entries[#entries+1]={canonical(entry[1]),canonical(entry[2])} end
    table.sort(entries,function(a,b) return E.encode(a[1])<E.encode(b[1]) end)
    return E.map(entries)
  elseif kind=='vector' then
    local items={}; for i,item in ipairs(value) do items[i]=canonical(item) end
    return E.vector(items)
  end
  return value
end
function M.emit(doc) return ';; Generated by love ir from the policy file. Do not edit.\n'..E.encode(canonical(doc))..'\n' end
function M.scan_policy(impl,p,filenames)
  -- An injected scan is an already-selected scanner; explicit declarations are
  -- still validated, but filename detection is unnecessary at this seam.
  local explicit=get(p,'lang') or get(p,'sources')
  local selected
  if explicit or not impl then selected=Detection.select(p,filenames) end
  local sources=get(p,'sources',V())
  if #sources>0 then
    local scans=V()
    for _,s in ipairs(sources) do
      local lang=get(s,'lang',get(p,'lang')); local opts=options(get(p,'prefix','uml-viewer'))
      E.assoc(opts,K('ns-prefix'),get(s,'prefix',get(p,'prefix','uml-viewer'))); E.assoc(opts,K('lang'),lang)
      local exclude=V(); for _,xs in ipairs{get(p,'exclude',V()),get(s,'exclude',V())} do for _,x in ipairs(xs) do local found=false; for _,v in ipairs(exclude) do if E.equal(x,v) then found=true end end; if not found then exclude[#exclude+1]=x end end end
      if #exclude>0 then E.assoc(opts,K('exclude'),exclude) end
      scans[#scans+1]=G.scan_project(lang,get(s,'root',get(s,'src',get(p,'src','src'))),opts)
    end
    return G.merge_scans(scans)
  end
  local opts=options(get(p,'prefix','uml-viewer')); local exclude=get(p,'exclude',V()); if #exclude>0 then E.assoc(opts,K('exclude'),exclude) end
  if impl then return invoke(impl,get(p,'src','src'),opts) end
  return G.scan_project(selected,get(p,'src','src'),opts)
end
function M.document(impl,p,filenames) return P.apply_policy(p,M.scan_policy(impl,p,filenames)) end
function M.generate(impl,path,out,adapter)
  local p=M.read_policy(path,adapter)
  local filenames
  if not impl and not get(p,'lang') and not get(p,'sources') then filenames=assert(adapter.filenames,'project filename snapshot required')() end
  local graph=M.scan_policy(impl,p,filenames)
  local extra=P.unassigned(p,graph); if #extra>0 and adapter.warn then local names={}; for _,c in ipairs(extra) do names[#names+1]=get(c,'ns','') end; adapter.warn('Unassigned namespaces: '..table.concat(names,', ')) end
  local doc=P.apply_policy(p,graph); E.assoc(doc,K('policy-file'),path)
  out=out or get(p,'out'); assert(type(out)=='string','output path required')
  adapter.write(out,M.emit(doc)); return out
end
return M
