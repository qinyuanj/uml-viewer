local E=require('uml.edn')
local D=require('uml.application.document')
local IR=require('uml.domain.ir')
describe('inspector public commands',function()
  it('lists only declared proposals and selects proposal or namespace through application events',function()
    local I=require('uml.application.inspector')
    local state=D.new(IR.read_document('{:hierarchical true :prefix "demo" :classes [{:id :a :ns "demo.a"}] :proposals [{:id :plan :name "中文方案" :layers []}]}'))
    local commands=I.commands(state); assert.are.equal('Real diagram',commands[1].label); assert.is_true(commands[1].active)
    assert.are.equal('中文方案',commands[2].label); assert.is_false(commands[2].active)
    local proposal,context=I.choose(state,E.keyword('plan')); assert.is_true(require('uml.domain.geom').get(proposal.extra,'proposal')); assert.is_true(E.equal(E.parse('{:context :proposal :proposal-id :plan :name "中文方案"}'),context))
    local real,realcontext=I.choose(proposal); assert.is_false(require('uml.domain.geom').get(real.extra,'proposal')); assert.is_true(E.equal(E.parse('{:context :real}'),realcontext))
    local empty=D.new(IR.read_document('{:hierarchical true :prefix "demo" :classes []}')); assert.are.equal(1,#I.commands(empty)); assert.are.equal(1,#I.commands(empty))
  end)
end)
