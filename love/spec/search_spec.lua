local E=require('uml.edn')
local G=require('uml.domain.geom')
local D=require('uml.application.document')
local I=require('uml.application.inspector')
local Events=require('uml.application.events')
local k,g=E.keyword,G.get
local function state()
  return D.new(E.parse('{:hierarchical true :classes [{:id :alpha.deep.parser :name "解析器" :ns "love.alpha.deep.parser"} {:id :beta.parser :name "解析器" :ns "love.beta.parser"}] :edges [{:from :alpha.deep.parser :to :beta.parser :kind :dependency}]}'),'one')
end
describe('cross-layer inspector search',function()
  it('activates a deep target, centering selection and details without changing discussion context',function()
    local s=state(); s.discussion_context={context='proposal',name='Keep'}
    local a=Events.locate(s,k('alpha.deep.parser'),{view_w=800,window_h=600})
    assert.is_true(E.equal(E.parse('[:alpha :deep]'),a.focus))
    assert.is_true(E.equal(k('alpha.deep.parser'),g(a.selected,'id')))
    assert.is_true(E.equal(k('alpha.deep.parser'),a.detail_id))
    assert.are.equal(s.discussion_context,a.discussion_context); assert.are.equal(s.document,a.document)
    local c=require('uml.engine.hit').class_by_id(a.scene,a.detail_id); local r=g(c,'rect')
    local x,y=Events.world_xy(a,400,300)
    assert.are.equal(g(r,'x')+g(r,'w')/2,x); assert.are.equal(g(r,'y')+g(r,'h')/2,y)
    assert.are.equal(a,Events.locate(a,k('gone'),{view_w=800,window_h=600}))
  end)
  it('locates nested proposal members in classes declutter while retaining the proposal',function()
    local s=state(); E.assoc(s.document,k('proposals'),E.parse('[{:id :split :name "Split" :layers [{:id :core :nses [{:id :nested :label "Nested" :nses [:alpha.deep.parser]}]} {:id :other :nses [:beta.parser]}]}]'))
    s=Events.show_proposal(s,k('split')); s.extra=E.parse('{:proposal-id :split :proposal true :declutter :classes}')
    local a=Events.locate(s,k('alpha.deep.parser'),{view_w=600,window_h=400})
    assert.is_true(E.equal(k('split'),g(a.extra,'proposal-id')))
    assert.is_true(E.equal(k('nested'),g(a.extra,'open-layer')))
    assert.is_true(E.equal(k('classes'),g(a.extra,'declutter')))
    assert.is_true(E.equal(k('alpha.deep.parser'),a.detail_id))
  end)
  it('resolves child detail identity and complete relations through the card scene',function()
    local s=state(); local Detail=require('uml.application.detail')
    local m=Detail.for_state(s,k('alpha.deep.parser'))
    assert.are.equal('解析器',g(m.class,'name'))
    assert.are.equal('love.alpha.deep.parser',m.ns)
    assert.are.equal('解析器',m.rels[1].name)
    local child=Events.open_detail(s,E.parse('{:kind :child :id :alpha.deep.parser :parent :alpha}'))
    assert.is_true(E.equal(k('alpha.deep.parser'),child.detail_id))
  end)
  it('refreshes matches on document replacement and rejects stale targets',function()
    local s=state(); local id=I.search(s,'alpha')[1].id
    local n=D.reload(s,'{:hierarchical true :classes [{:id :replacement :name "替代"}] :edges []}','two')
    assert.are.equal(0,#I.search(n,'alpha'))
    assert.are.equal(n,Events.locate(n,id,{view_w=500,window_h=400}))
    assert.are.equal(1,#I.search(n,'替代'))
  end)
  it('matches Chinese names and full namespaces throughout the loaded document',function()
    local s=state(); local results=I.search(s,'解析')
    assert.are.equal(2,#results)
    assert.are.equal('love.alpha.deep.parser',results[1].ns)
    assert.are.equal('love.beta.parser',results[2].ns)
    assert.are.equal(1,#I.search(s,'LOVE.ALPHA.DEEP'))
    assert.are.equal(0,#I.search(s,''))
  end)
end)
