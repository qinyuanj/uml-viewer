local E=require('uml.edn')
local D=require('uml.application.document')
local IR=require('uml.domain.ir')
local function scene(text) return require('uml.engine.compose').compile_diagram(IR.normalize(E.parse(text))) end
local function find(rows,key,value) for _,r in ipairs(rows) do if r[key]==value then return r end end end
local tiny=[[{:title "Tiny" :packages [{:id :p :label "Domain" :classes [{:id :a :name "A" :ns "demo.a" :coverage 0.9 :crap 1.2 :ops [{:name "go" :args ["x"] :returns "void" :coverage 0.75 :cc 2 :crap 1.8 :killed 3 :survived 1 :uncovered 2 :sites 6} {:name "hide" :private true :crap 4.0}]} {:id :b :name "B"}]}] :edges [{:from :a :to :b :kind :dependency}]}]]
describe('detail public class card',function()
  it('reserves a 20px detail title row followed by 18px body rows',function()
    local rows=require('uml.application.detail').rows({class={name='中文类名',level=2},ns='demo.a'})
    assert.are.equal(0,rows[1].y); assert.are.equal(20,rows[1].h)
    assert.are.equal(20,rows[2].y); assert.are.equal(18,rows[2].h)
    assert.are.equal(38,rows[3].y)
  end)
  it('lays out all six metric columns and the two group spans',function()
    local Detail=require('uml.application.detail'); local cols=Detail.column_layout(); local groups=Detail.group_layout()
    local labels={}; for _,c in ipairs(cols) do labels[#labels+1]=c.label end
    assert.are.same({'Crap','CC','Cov','killed','survived','uncovered'},labels)
    assert.are.equal(252,cols[1].left); assert.are.equal(624,cols[6].right)
    assert.are.same({{id='crap',label='--crap--',left=252,right=404},{id='mutation',label='--mutation--',left=414,right=624}},groups)
  end)
  it('preserves all optional identity, mutation and source label rules',function()
    local Detail=require('uml.application.detail')
    assert.are.equal(32,Detail.content_h({})); assert.is_nil(Detail.rows(nil))
    assert.are.same({'Solo','包  orphan'},(function() local t={}; for _,r in ipairs(Detail.rows({class={name='Solo',package=E.keyword('orphan')}})) do t[#t+1]=r.text end; return t end)())
    for _,case in ipairs{{'src/lib.rs','demo.rust','lib.rs',false},{'src/PROTO.RS','demo.rust','PROTO.RS',false},{'src/lib.rs','demo.rust','demo.rust',true},{'src/model.ts','demo.model','demo.model',false},{'src/graph_python.py','demo.graph-python','demo.graph-python',false}} do
      local rows=Detail.rows({class={name='Module',['drill?']=case[4]},file=case[1],ns=case[2]}); assert.are.equal(case[3],find(rows,'module',true).text)
    end
    local rows=Detail.rows({class={name='D',level=2,stereotype=E.keyword('bean'),crap={mu=14.2,max=134.6,sigma=34.9},cc=65,killed=5,survived=1,uncovered=0,sites=0,fields={{text='n'}},ops={{name='go',text='go()',killed=0,survived=0,uncovered=0,sites=4}}},rels={{id=E.keyword('b'),phrase='依赖',name='B',label='db'}}})
    assert.is_not_nil(find(rows,'text','层级 2')); assert.is_not_nil(find(rows,'text','«bean»')); assert.is_not_nil(find(rows,'text','n')); assert.is_not_nil(find(rows,'text','依赖  B  «db»'))
    assert.are.equal('Crap μ 14.2 max 134.6 σ 34.9',find(rows,'kind','crap').text)
    local cls=find(rows,'crap-s','14.2μ'); assert.is_nil(cls['cc-s']); assert.is_nil(cls['mut-note']); assert.are.equal('5',cls['killed-s'])
    local op=find(rows,'op-name','go'); assert.is_nil(op['mut-note']); assert.are.equal('0',op['killed-s'])
    assert.are.equal(rows[#rows].y+34,Detail.content_h(rows)); assert.is_nil(Detail.rel_at(rows,16)); assert.is_nil(Detail.member_at(rows,op.y+op.h)); assert.is_false(Detail.module_at(rows,16))
    assert.is_nil(find(Detail.rows({class={name='Only uncovered',uncovered=4}}),'kind','stats'))
    for _,metric in ipairs{'coverage','cc','killed','survived'} do assert.is_not_nil(find(Detail.rows({class={name='Zero',[metric]=0}}),'kind','stats')) end
    assert.are.same({ns='demo.a',lang=E.keyword('rust'),file='src/lib.rs'},Detail.member_ident({ns='demo.a',lang=E.keyword('rust'),file='src/lib.rs'},''))
  end)
  it('describes every relationship kind in both directions and falls back for unknown kinds',function()
    local Detail=require('uml.application.detail')
    for _,case in ipairs{{'inheritance','继承','被继承'},{'implements','实现','被实现'},{'association','关联','被关联'},{'dependency','依赖','被依赖'},{'aggregation','聚合','被聚合'},{'composition','组合','被组合'},{'other','指向','来自'}} do
      local s=E.parse('{:classes [{:id :a :name "A"} {:id :b :name "B"}] :edges [{:from :a :to :b :kind :'..case[1]..'}]}')
      assert.are.equal(case[2],Detail.model(s,E.keyword('a')).rels[1].phrase); assert.are.equal(case[3],Detail.model(s,E.keyword('b')).rels[1].phrase)
    end
  end)
  it('retains aggregate namespace and leaf relationships across root and focused cards without duplicates',function()
    local Detail=require('uml.application.detail')
    local doc=IR.read_document('{:hierarchical true :classes [{:id :alpha.deep.parser} {:id :beta.parser}] :edges [{:from :alpha.deep.parser :to :beta.parser :kind :dependency}]}')
    local state=D.new(doc)
    local root=Detail.for_state(state,E.keyword('alpha'))
    assert.are.equal(1,#root.rels); assert.is_true(E.equal(E.keyword('beta'),root.rels[1].id))
    local leaf=Detail.for_state(state,E.keyword('alpha.deep.parser'))
    assert.are.equal(1,#leaf.rels); assert.is_true(E.equal(E.keyword('beta.parser'),leaf.rels[1].id))
    state.focus=E.vector{E.keyword('alpha')}
    state.scene=D.compile_view(doc,nil,state.focus)
    local focused=Detail.for_state(state,E.keyword('alpha.deep'))
    assert.is_not_nil(focused)
    assert.are.equal(1,#Detail.for_state(state,E.keyword('alpha')).rels)
    assert.are.equal(1,#Detail.for_state(state,E.keyword('alpha.deep.parser')).rels)
  end)
  it('opens an intermediate namespace port with its aggregate relationships from another layer',function()
    local Detail=require('uml.application.detail')
    local doc=IR.read_document('{:hierarchical true :classes [{:id :alpha.deep.parser} {:id :beta.deep.user}] :edges [{:from :alpha.deep.parser :to :beta.deep.user :kind :dependency}]}')
    local state=D.new(doc,nil,E.parse('[:beta :deep]'))
    state=require('uml.application.events').open_detail(state,E.parse('{:kind :port :id :alpha.deep :parent :beta.deep.user}'))
    assert.is_true(E.equal(E.keyword('alpha.deep'),state.detail_id))
    local port=Detail.for_state(state,state.detail_id)
    assert.is_not_nil(port); assert.are.equal(1,#port.rels)
    assert.is_true(E.equal(E.keyword('beta'),port.rels[1].id))
    local located=require('uml.application.events').locate(state,port.rels[1].id,{view_w=1000,window_h=800})
    assert.is_true(E.equal(E.keyword('beta'),located.detail_id)); assert.are.equal(0,#located.focus)
    assert.are.equal(located,require('uml.application.events').locate(located,E.keyword('missing'),{}))
    assert.are.equal(1,#Detail.for_state(state,E.keyword('alpha.deep.parser')).rels)
  end)
  it('clamps detail-card scrolling to the content and viewport bounds',function()
    local Detail=require('uml.application.detail')
    local rows=Detail.rows(Detail.model(scene(tiny),E.keyword('a'))); local content=Detail.content_h(rows)
    assert.are.equal(0,Detail.max_scroll(rows,content))
    assert.are.equal(content,Detail.max_scroll(rows,0))
    assert.are.equal(0,Detail.max_scroll(nil,100))
    assert.are.equal(0,Detail.scroll(rows,100,0,-1))
    assert.are.equal(Detail.scroll_step,Detail.scroll(rows,100,0,1))
    assert.are.equal(Detail.scroll_step*2,Detail.scroll(rows,100,Detail.scroll_step,1))
    assert.are.equal(content-100,Detail.scroll(rows,100,0,9999))
    assert.are.equal(0,Detail.scroll(rows,100,content-100,-9999))
  end)
  it('highlights only the hovered operation or module row',function()
    local Detail=require('uml.application.detail')
    local rows=Detail.rows(Detail.model(scene(tiny),E.keyword('a')))
    assert.are.same(find(rows,'op-name','go'),Detail.highlight(rows,'go'))
    assert.is_nil(Detail.highlight(rows,'A'))
    assert.is_nil(Detail.highlight(rows,'absent'))
    assert.is_nil(Detail.highlight(rows,nil))
    assert.are.same(find(rows,'module',true),Detail.highlight(rows,E.keyword('module')))
    assert.are.same(find(rows,'op-name','hide'),Detail.highlight(rows,'hide'))
  end)
  it('shows class and member quality, source identity and relationship hits',function()
    local Detail=require('uml.application.detail')
    local model=Detail.model(scene(tiny),E.keyword('a')); local rows=Detail.rows(model)
    assert.are.equal('demo.a',model.ns)
    local cls=find(rows,'text','A'); assert.are.equal('name',cls.kind)
    cls=find(rows,'crap-s','1.2μ'); assert.are.equal('90%',cls['cov-s']); assert.is_nil(cls['cc-s']); assert.are.equal('3',cls['killed-s'])
    local go=find(rows,'op-name','go'); assert.are.equal('+ go(x) : void',go.text); assert.are.equal('75%',go['cov-s']); assert.are.equal('2',go['cc-s']); assert.are.equal('1.8',go['crap-s'])
    assert.are.equal('go',Detail.member_at(rows,go.y+1)); assert.is_nil(Detail.member_at(rows,cls.y))
    local hide=find(rows,'op-name','hide'); assert.are.equal('- hide',hide.text); assert.is_true(hide.private); assert.are.equal('---无 mutation 位点---',hide['mut-note'])
    local rel=find(rows,'kind','rel'); assert.are.equal('依赖  B',rel.text); assert.is_true(E.equal(E.keyword('b'),Detail.rel_at(rows,rel.y+1)))
    local mod=find(rows,'module',true); assert.is_true(Detail.module_at(rows,mod.y)); assert.is_false(Detail.module_at(rows,go.y))
    assert.are.same({ns='demo.a',name='go'},Detail.member_ident(model,'go'))
    assert.is_nil(Detail.model(scene(tiny),E.keyword('absent')))
  end)
end)
