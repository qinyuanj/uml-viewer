local edn=require('uml.edn')
local file=require('uml.adapters.edn_file')

describe('atomic EDN files',function()
  local path
  before_each(function() path=os.tmpname(); os.remove(path) end)
  after_each(function() os.remove(path) end)
  it('creates and replaces an existing target while preserving semantic values',function()
    file.write(path,edn.parse('{:queue [] :next-id 1}'))
    file.write(path,edn.parse('{:queue [{:op :display}] :next-id 2}'))
    assert.is_true(edn.equal(edn.parse('{:queue [{:op :display}] :next-id 2}'),file.read(path)))
  end)
  it('replaces paths containing spaces and shell metacharacters literally',function()
    local special=path.." space %PATH% & 'quoted'.edn"
    local ok,message=pcall(function()
      file.write(special,edn.parse('{:next-id 1}'))
      file.write(special,edn.parse('{:next-id 2}'))
      assert.is_true(edn.equal(edn.parse('{:next-id 2}'),file.read(special)))
    end)
    os.remove(special)
    assert.is_true(ok,message)
  end)
  it('leaves the previous destination intact when encoding fails',function()
    file.write(path,edn.parse('{:next-id 7}'))
    assert.has_error(function() file.write(path,function() end) end)
    assert.is_true(edn.equal(edn.parse('{:next-id 7}'),file.read(path)))
  end)
  it('keeps the old destination when the replacement boundary fails',function()
    file.write(path,edn.parse('{:next-id 7}'))
    local replacement=require('uml.adapters.atomic_file')
    assert.has_error(function()
      replacement.write(path,'new',function() return nil,'simulated sharing violation' end)
    end)
    assert.is_true(edn.equal(edn.parse('{:next-id 7}'),file.read(path)))
  end)
end)
