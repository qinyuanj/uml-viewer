local edn=require('uml.edn')
local function same(expected,actual)
  assert.is_true(edn.equal(edn.parse(expected),actual),edn.encode(actual))
end

describe('policy to IR',function()
  it('places scanned Lua namespaces in a hierarchy without inventing proposals',function()
    local policy=require('uml.domain.policy')
    same('{:title "UML" :hierarchical true :prefix "uml-viewer" :order [] :levels [] :edge-kinds {} :omit-edges [] :omit [] :classes [{:id :calc :name "Calc" :ns "calc" :lang :lua :file "src/calc/init.lua"}] :edges []}',
      policy.apply_policy(edn.parse('{}'),edn.parse('{:classes [{:id :calc :name "Calc" :ns "calc" :lang :lua :file "src/calc/init.lua"}] :edges []}')))
  end)
  it('collapses declared foreign namespaces, filters missing endpoints and bundles directed edges',function()
    local p=require('uml.domain.policy')
    local doc=p.apply_policy(edn.parse('{:foreign [:socket :socket.http]}'),edn.parse([[{:classes [{:id :calc :name "Calc"} {:id :socket.http.client :foreign true} {:id :socket.udp :foreign true} {:id :unknown :foreign true}]
      :edges [{:from :calc :to :socket.http.client :kind :dependency} {:from :calc :to :socket.http.client :kind :association :note "first"} {:from :calc :to :socket.http.client :kind :association :note "last"} {:from :calc :to :socket.udp :kind :dependency} {:from :calc :to :unknown :kind :dependency} {:from :calc :to :missing :kind :dependency} {:from :calc :to :calc :kind :dependency}]}]]))
    same('[{:id :calc :name "Calc"} {:id :socket :name "socket" :foreign true} {:id :socket.http :name "socket.http" :foreign true}]',edn.get(doc,edn.keyword('classes')))
    same('[{:from :calc :to :socket.http :kind :association :note "last"} {:from :calc :to :socket :kind :dependency}]',edn.get(doc,edn.keyword('edges')))
  end)
  it('preserves named proposals with nested namespace groups and stamps longest-prefix ranks including zero',function()
    local p=require('uml.domain.policy')
    local doc=p.apply_policy(edn.parse([=[{:levels [[:calc] [:calc.io]] :proposals [{:id :plan :name "计算" :omit ["calc.old"] :layers [{:label "计算" :nses [:calc {:label "IO" :nses [calc.io]}]}]}] :omit [:calc.old] :edge-kinds {[:calc :calc.io] :association}}]=]),edn.parse([[{:classes [{:id :calc :name "Calc"} {:id :calc.io.read :name "Read"}]
      :edges [{:from :calc :to :calc.io.read :kind :dependency} {:from :calc.io.read :to :calc :kind :dependency :violating true}]}]]))
    same('[[:calc] [:calc.io]]',edn.get(doc,edn.keyword('levels')))
    same('[{:id :calc :name "Calc" :level 0} {:id :calc.io.read :name "Read" :level 1}]',edn.get(doc,edn.keyword('classes')))
    same('[{:from :calc :to :calc.io.read :kind :dependency :violating true} {:from :calc.io.read :to :calc :kind :dependency}]',edn.get(doc,edn.keyword('edges')))
    same('[{:id :plan :name "计算" :omit [:calc.old] :notice "PROPOSAL — not instantiated in code" :layers [{:id :计算 :label "计算" :nses [:calc {:id :IO :label "IO" :nses [:calc.io]}]}]}]',edn.get(doc,edn.keyword('proposals')))
    same('{[:calc :calc.io] :association}',edn.get(doc,edn.keyword('edge-kinds')))
  end)
  it('builds legacy package diagrams with Unassigned, outgoing stubs and foreign ovals',function()
    local p=require('uml.domain.policy')
    local doc=p.apply_policy(edn.parse([=[{:title "Calc" :foreign [:socket] :packages [{:id :calc :label "Calc" :nses [:calc]}] :diagrams [{:title "All" :view :overview :hide-members true} {:title "Calc" :package :calc :edge-kinds {[:calc :util] :association}}]}]=]),edn.parse([=[{:classes [{:id :calc :name "Calc" :ns "demo.calc" :lang :lua :file "src/calc.lua" :stereotype :interface} {:id :util :name "Util"} {:id :orphan :name "Orphan"} {:id :socket.http :foreign true}]
      :edges [{:from :calc :to :util :kind :dependency} {:from :calc :to :socket.http :kind :dependency} {:from :util :to :orphan :kind :dependency}]}]=]))
    local diagrams=edn.get(doc,edn.keyword('diagrams'))
    same('{:title "All" :direction :tb :packages [{:id :calc :label "Calc" :classes [{:id :calc :name "Calc" :ns "demo.calc" :lang :lua :file "src/calc.lua" :stereotype :interface :hide-members true}]} {:id :unassigned :label "Unassigned" :classes [{:id :orphan :name "Orphan" :hide-members true} {:id :util :name "Util" :hide-members true}]}] :foreign [{:id :socket :name "socket" :shape :oval}] :edges [{:from :calc :to :util :kind :dependency} {:from :calc :to :socket :kind :dependency} {:from :util :to :orphan :kind :dependency}]}',diagrams[1])
    same('{:title "Calc" :direction :lr :packages [{:id :calc :label "Calc" :classes [{:id :calc :name "Calc" :ns "demo.calc" :lang :lua :file "src/calc.lua" :stereotype :interface} {:id :util :name "Util" :hide-members true}]}] :foreign [{:id :socket :name "socket" :shape :oval}] :edges [{:from :calc :to :util :kind :association} {:from :calc :to :socket :kind :dependency}]}',diagrams[2])
  end)
  it('uses legacy nested proposal layers as ranks and preserves hierarchy view directives',function()
    local p=require('uml.domain.policy')
    local doc=p.apply_policy(edn.parse([=[{:hierarchical false :order [calc] :omit [calc.old] :omit-edges [[:calc :io]] :proposal [{:nses [:calc {:label "IO" :nses [:io]}]} {:id :host :nses [:host]}]}]=]),edn.parse('{:classes [{:id :calc :name "Calc"} {:id :io :name "Io"} {:id :host :name "Host"}] :edges [{:from :calc :to :host :kind :dependency} {:from :host :to :calc :kind :association}]}'))
    same('[[:calc :io] [:host]]',edn.get(doc,edn.keyword('levels')))
    same('[{:from :calc :to :host :kind :dependency :violating true} {:from :host :to :calc :kind :association}]',edn.get(doc,edn.keyword('edges')))
    same('[:calc.old]',edn.get(doc,edn.keyword('omit')))
    same('[[:calc :io]]',edn.get(doc,edn.keyword('omit-edges')))
    same('[:calc]',edn.get(doc,edn.keyword('order')))
    same(':layer-0',edn.get(edn.get(edn.get(doc,edn.keyword('proposal')),edn.keyword('layers'))[1],edn.keyword('id')))
  end)
  it('restamps proposal IR and applies directed vector-key overrides without stale violations',function()
    local p=require('uml.domain.policy')
    local ranks=p.ranks_from_layers(edn.parse('[{:nses [:io]} {:nses [:calc]}]'))
    local stamped=p.restamp_ranks(edn.parse('[{:id :calc :level 0} {:id :io :level 1} {:id :other :level 9} {:id :io.external :foreign true :level 7}]'),edn.parse('[{:from :calc :to :io :kind :dependency :violating true} {:from :io :to :calc :kind :dependency}]'),ranks)
    same('[{:id :calc :level 1} {:id :io :level 0} {:id :other} {:id :io.external :foreign true}]',edn.get(stamped,edn.keyword('classes')))
    same('[{:from :calc :to :io :kind :dependency} {:from :io :to :calc :kind :dependency :violating true}]',edn.get(stamped,edn.keyword('edges')))
    local edges=p.apply_edge_kinds(edn.get(stamped,edn.keyword('edges')),edn.parse('{[:io :calc] :association}'),edn.parse('[["calc" "io"]]'))
    same('[{:from :io :to :calc :kind :association}]',edges)
  end)
  it('distinguishes explicit empty package mode and empty named proposals from absent values',function()
    local p=require('uml.domain.policy')
    same('{:title "UML" :diagrams []}',p.apply_policy(edn.parse('{:title nil :packages [] :diagrams []}'),edn.parse('{:classes [] :edges []}')))
    local doc=p.apply_policy(edn.parse('{:title false :prefix nil :proposals [] :proposal [{:nses [:calc]}]}'),edn.parse('{:classes [{:id :calc}] :edges []}'))
    assert.is_nil(edn.get(doc,edn.keyword('proposals')))
    same('"UML"',edn.get(doc,edn.keyword('title')))
    same('"uml-viewer"',edn.get(doc,edn.keyword('prefix')))
    same('[[:calc]]',edn.get(doc,edn.keyword('levels')))
    assert.has_error(function() p.apply_policy(edn.parse('{:packages [] :diagrams [{:package :missing}]}'),edn.parse('{:classes [] :edges []}')) end)
  end)
  it('marks only outward dependencies and keeps strongest relationship kinds',function()
    local p=require('uml.domain.policy')
    local doc=p.apply_policy(edn.parse('{:levels [[:calc :same] [:io]]}'),edn.parse([=[{:classes [{:id :calc} {:id :same} {:id :io} {:id :unknown}]
      :edges [{:from :calc :to :io :kind :dependency} {:from :calc :to :io :kind :implements}
              {:from :io :to :calc :kind :dependency} {:from :calc :to :same :kind :dependency}
              {:from :calc :to :unknown :kind :dependency} {:from :same :to :io :kind :association}
              {:from :unknown :to :calc :kind :dependency}]}]=]))
    same('[{:from :calc :to :io :kind :implements} {:from :io :to :calc :kind :dependency} {:from :calc :to :same :kind :dependency} {:from :calc :to :unknown :kind :dependency} {:from :same :to :io :kind :association} {:from :unknown :to :calc :kind :dependency}]',edn.get(doc,edn.keyword('edges')))
    assert.is_true(p.omitted_id(edn.keyword('calc.io'),edn.parse('[:calc]')))
    assert.is_true(p.omitted_id(edn.keyword('calc'),edn.parse('[:calc]')))
    assert.is_false(p.omitted_id(edn.keyword('calculator'),edn.parse('[:calc]')))
    assert.is_false(p.omitted_id(edn.keyword('io'),edn.parse('[:calc]')))
  end)
  it('retains bundled dependency violations until a stronger relationship replaces them',function()
    local p=require('uml.domain.policy')
    same('[{:from :calc :to :io :kind :dependency :violating true :note "later"}]',p.merge_edges(edn.parse('[{:from :calc :to :io :kind :dependency :violating true} {:from :calc :to :io :kind :dependency :note "later"}]')))
    same('[{:from :calc :to :io :kind :inheritance}]',p.merge_edges(edn.parse('[{:from :calc :to :io :kind :implements :violating true} {:from :calc :to :io :kind :inheritance}]')))
  end)
  it('preserves JVM grouped directed-pair order in public IR after array-map promotion',function()
    local p=require('uml.domain.policy')
    local graph=edn.parse([[{:classes [{:id :app} {:id :model} {:id :dogs} {:id :dogs.kennel} {:id :os} {:id :extra} {:id :fs} {:id :typing} {:id :service} {:id :json} {:id :cli}]
      :edges [{:from :app :to :model} {:from :dogs :to :model} {:from :dogs :to :dogs.kennel} {:from :dogs.kennel :to :model} {:from :dogs.kennel :to :os} {:from :extra :to :model} {:from :extra :to :os} {:from :fs :to :typing} {:from :service :to :model} {:from :service :to :json} {:from :cli :to :model}]}]])
    -- Clojure 1.12.0 policy/apply-policy, unchanged Python golden pair order.
    same('[{:from :fs :to :typing} {:from :dogs.kennel :to :model} {:from :service :to :model} {:from :dogs.kennel :to :os} {:from :app :to :model} {:from :dogs :to :model} {:from :service :to :json} {:from :dogs :to :dogs.kennel} {:from :cli :to :model} {:from :extra :to :model} {:from :extra :to :os}]',edn.get(p.apply_policy(edn.parse('{}'),graph),edn.keyword('edges')))
  end)
  it('counts distinct pairs at the eight-entry boundary and keeps duplicate metadata',function()
    local p=require('uml.domain.policy')
    local graph=edn.parse('{:classes [{:id :目标/终点}] :edges []}')
    local classes,edges=edn.get(graph,edn.keyword('classes')),edn.get(graph,edn.keyword('edges'))
    local names={'团队/计算','a','b','c','d','e','f','g','h'}
    local function add(n)
      classes[#classes+1]=edn.parse('{:id :'..n..'}')
      edges[#edges+1]=edn.parse('{:from :'..n..' :to :目标/终点 :kind :dependency}')
    end
    for i=1,8 do add(names[i]) end
    edges[#edges+1]=edn.parse('{:from :团队/计算 :to :目标/终点 :kind :dependency :note "last" :violating true}')
    local function pairs_in_ir()
      local result=edn.vector()
      for _,e in ipairs(edn.get(p.apply_policy(edn.parse('{}'),graph),edn.keyword('edges'))) do
        result[#result+1]=edn.vector{edn.get(e,edn.keyword('from')),(edn.get(e,edn.keyword('to')))}
        if edn.equal(edn.get(e,edn.keyword('from')),edn.keyword(names[1])) then
          assert.equals('last',edn.get(e,edn.keyword('note')))
        end
      end
      return result
    end
    -- Independently captured with Clojure 1.12.0 group-by, including an update.
    same('[[:团队/计算 :目标/终点] [:a :目标/终点] [:b :目标/终点] [:c :目标/终点] [:d :目标/终点] [:e :目标/终点] [:f :目标/终点] [:g :目标/终点]]',pairs_in_ir())
    add(names[9])
    same('[[:b :目标/终点] [:d :目标/终点] [:c :目标/终点] [:f :目标/终点] [:h :目标/终点] [:a :目标/终点] [:团队/计算 :目标/终点] [:g :目标/终点] [:e :目标/终点]]',pairs_in_ir())
  end)
  for _,language in ipairs({'lua','rust','typescript','python'}) do
    it('retains exact '..language..' JVM golden edge vectors through public IR',function()
      local f=assert(io.open('fixtures/jvm-goldens/'..language..'.ir.edn','rb'))
      local golden=edn.parse(f:read('*a')); f:close()
      local pf=assert(io.open(language..'-fixture/policy.edn','rb'))
      local policy=edn.parse(pf:read('*a')); pf:close()
      local doc=require('uml.domain.policy').apply_policy(policy,golden)
      assert.is_true(edn.equal(edn.get(golden,edn.keyword('edges')),edn.get(doc,edn.keyword('edges'))),edn.encode(edn.get(doc,edn.keyword('edges'))))
    end)
  end
  it('accepts a timestamp-named proposal without inventing it during IR generation',function()
    local p=require('uml.domain.policy')
    local name=p.timestamp_name(0)
    assert.is_truthy(name:match('^%d%d%d%d%-%d%d%-%d%d %d%d:%d%d:%d%d$'))
    local policy=edn.parse('{:proposals [{:layers []}]}')
    edn.assoc(edn.get(policy,edn.keyword('proposals'))[1],edn.keyword('name'),name)
    local doc=p.apply_policy(policy,edn.parse('{:classes [] :edges []}'))
    assert.are.equal(name,edn.get(edn.get(doc,edn.keyword('proposals'))[1],edn.keyword('name')))
    assert.is_nil(edn.get(doc,edn.keyword('proposal')))
  end)
end)
