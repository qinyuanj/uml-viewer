local log=require('uml.adapters.log')
local compat=require('uml.compat')
describe('viewer log',function()
  local path
  before_each(function() path=os.tmpname() end)
  after_each(function() os.remove(path) end)
  it('appends traceback and optional reload context',function()
    log.exception('boom','reload examples/x.edn',path)
    log.exception('again',nil,path)
    local f=assert(io.open(path)); local body=f:read('*a'); f:close()
    assert.is_truthy(body:find('reload examples/x.edn',1,true))
    assert.is_truthy(body:find('boom',1,true))
    assert.is_truthy(body:find('again',1,true))
    assert.is_truthy(body:find('stack traceback',1,true))
  end)
  it('provides an uncaught error handler that logs and returns traceback',function()
    local ok,message=xpcall(function() error('untamed') end,log.handler(path,'uncaught on viewer'))
    assert.is_false(ok)
    assert.is_truthy(message:find('untamed',1,true))
    local f=assert(io.open(path)); local body=f:read('*a'); f:close()
    assert.is_truthy(body:find('uncaught on viewer',1,true))
  end)
  it('does not throw when the log cannot be opened',function()
    assert.has_no.errors(function() log.exception('boom',nil,path..'/missing/log') end)
  end)
end)
describe('Lua compatibility',function()
  it('unpacks explicit ranges including nil positions',function()
    local a,b,c=compat.unpack({'a',nil,'c'},1,3)
    assert.are.equal('a',a); assert.is_nil(b); assert.are.equal('c',c)
  end)
end)
