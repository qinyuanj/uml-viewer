local JSON=require('uml.adapters.json')
describe('Herdr JSON boundary',function()
  it('decodes nested objects, arrays, strings, numbers and booleans',function()
    local value=JSON.decode('{"session":"s","socket":"C:/x/herdr.sock","running":true,"protocol":22,'
      ..'"panes":[{"pane_id":"w1:p1","terminal_id":"t"}],"none":null,"escaped":"a\\"b\\\\c\\n"}')
    assert.are.equal('s',value.session)
    assert.are.equal('C:/x/herdr.sock',value.socket)
    assert.is_true(value.running)
    assert.are.equal(22,value.protocol)
    assert.is_true(JSON.is_array(value.panes))
    assert.are.equal('w1:p1',value.panes[1].pane_id)
    assert.are.equal('a"b\\c\n',value.escaped)
    assert.is_equal(JSON.null,value.none)
  end)
  it('keeps empty arrays distinct from empty objects',function()
    local value=JSON.decode('{"panes":[],"info":{}}')
    assert.is_true(JSON.is_array(value.panes))
    assert.are.equal(0,#value.panes)
    assert.is_false(JSON.is_array(value.info))
  end)
  it('encodes arrays and objects without losing literal argv text',function()
    local text=JSON.encode(JSON.array{'a b','$HOME','it\'s',JSON.array{1,2},'中文',''})
    local back=JSON.decode(text)
    assert.are.equal('a b',back[1]); assert.are.equal('$HOME',back[2]); assert.are.equal("it's",back[3])
    assert.are.equal(2,back[4][2]); assert.are.equal('中文',back[5]); assert.are.equal('',back[6])
  end)
  it('rejects malformed documents instead of guessing',function()
    for _,text in ipairs{'','{','[1,]','"unterminated','tru','{"a" 1}'} do
      assert.has_error(function() JSON.decode(text) end)
    end
  end)
end)
