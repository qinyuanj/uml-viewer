local E=require('uml.edn')
local G=require('uml.domain.geom')
local D=require('uml.application.document')
local Events=require('uml.application.events')
local Hit=require('uml.engine.hit')
local g,k=G.get,E.keyword
local function state()
  return D.new(E.parse('{:hierarchical true :title "Tree" :classes [{:id :source} {:id :source.lua} {:id :source.lua.parser} {:id :other}] :edges []}'),'one')
end
-- Screen point inside the top band of a class box (zoom 1, camera 0).
local function at(s,id) local r=g(Hit.class_by_id(s.scene,k(id)),'rect'); return g(r,'x')+5,g(r,'y')+5 end
describe('detail window transitions',function()
  it('keeps related classes outside the current namespace available to detail and source navigation',function()
    local Detail=require('uml.application.detail')
    local s=D.new(E.parse('{:hierarchical true :classes [{:id :app.a :ns "app.a" :file "a.lua" :ops [{:name "go"}]} {:id :other.b :ns "other.b" :file "b.lua"}] :edges [{:from :app.a :to :other.b :kind :dependency}]}'))
    s=Events.drill(s,k('app'))
    local a=assert(Detail.for_state(s,k('app.a')))
    assert.are.equal(1,#a.rels)
    local b=assert(Detail.for_state(s,a.rels[1].id))
    assert.are.equal('b.lua',Detail.member_ident(b).file)
  end)
  it('names the class behind a class, child row or port selection and nothing else',function()
    assert.is_true(E.equal(k('a'),Events.detail_id_for(E.parse('{:kind :class :id :a}'))))
    assert.is_true(E.equal(k('p'),Events.detail_id_for(E.parse('{:kind :child :id :c :parent :p}'))))
    assert.is_true(E.equal(k('p'),Events.detail_id_for(E.parse('{:kind :port :id :x :parent :p}'))))
    assert.is_nil(Events.detail_id_for(E.parse('{:kind :package :id :pkg}')))
    assert.is_nil(Events.detail_id_for(E.parse('{:kind :edge :from :a :to :b}')))
    assert.is_nil(Events.detail_id_for(nil))
  end)
  it('opens the detail for a leaf class on double press without leaving the layer',function()
    local s=state(); local x,y=at(s,'other')
    local n=Events.on_double_press(s,x,y)
    assert.is_true(E.equal(k('other'),n.detail_id)); assert.is_true(E.equal(k('other'),g(n.selected,'id')))
    assert.are.equal(0,#n.focus)
  end)
  it('drills a namespace on double press instead of opening its detail',function()
    local s=state(); local x,y=at(s,'source')
    local n=Events.on_double_press(s,x,y)
    assert.is_true(E.equal(E.parse('[:source]'),n.focus)); assert.is_nil(n.detail_id)
  end)
  it('keeps the detail closed on a single press and on empty canvas',function()
    local s=state(); local x,y=at(s,'other')
    assert.is_nil(Events.on_press(s,x,y).detail_id)
    assert.is_nil(Events.on_double_press(s,-5000,-5000).detail_id)
  end)
  it('resets detail scroll when the detail target switches, and keeps it for the same target',function()
    local s=state(); s.detail_id=k('other'); s.detail_scroll=96
    local same=Events.open_detail(s,E.parse('{:kind :class :id :other}'))
    assert.are.equal(96,same.detail_scroll)
    local other=Events.open_detail(s,E.parse('{:kind :class :id :source}'))
    assert.are.equal(0,other.detail_scroll); assert.is_true(E.equal(k('source'),other.detail_id))
    local x,y=at(s,'source')
    assert.are.equal(0,Events.on_press(s,x,y).detail_scroll)
  end)
  it('opens a child or port parent detail on single press',function()
    local s=state()
    s.scene=G.map{classes=E.vector{G.map{id=k('a'),rect=G.rect(0,50,120,120),lines=E.vector{G.map{kind=k('child'),id=k('child')}},['in-ports']=E.vector{G.map{id=k('port'),rect=G.rect(0,130,20,20)}}}},packages=E.vector(),edges=E.vector()}
    assert.is_true(E.equal(k('a'),Events.on_press(s,20,70).detail_id))
    assert.is_true(E.equal(k('a'),Events.on_press(s,5,135).detail_id))
  end)
  it('closes the detail window without clearing the selection; escape leaves the detail alone',function()
    local s=state(); s.detail_id=k('other'); s.selected=E.parse('{:kind :class :id :other}')
    local closed=Events.close_detail(s)
    assert.is_nil(closed.detail_id); assert.is_true(E.equal(s.selected,closed.selected))
    assert.is_true(E.equal(k('other'),Events.on_key(s,'escape').detail_id))
  end)
end)
