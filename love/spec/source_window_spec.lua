local Window=require('uml.adapters.source_window')
local Source=require('uml.main.source')
describe('source window public capability',function()
  it('opens source identities carrying the document language keyword',function()
    local window=Window.new(nil,{source=Source,is_file=function() return true end,read=function() return 'function M.load() end' end})
    assert.is_true(window.open({lang=require('uml.edn').keyword('lua'),file='model.lua',name='M.load'}))
    assert.equal(1,window.view().line)
  end)
  it('does not replace the open source window when a member is absent',function()
    local window=Window.new(nil,{source=Source,is_file=function() return true end,read=function() return 'function M.load() end\\n' end})
    assert.is_true(window.open({lang='lua',file='model.lua'}))
    local before=window.view()
    assert.is_nil(window.open({lang='lua',file='model.lua',name='missing'}))
    assert.same(before,window.view())
    window.close(); assert.is_nil(window.view())
  end)
  it('opens an empty file as one numbered module row without highlight',function()
    local window=Window.new(nil,{source=Source,is_file=function() return true end,read=function() return '' end})
    assert.is_true(window.open({lang='lua',file='empty.lua',name=''}))
    assert.same({title='empty.lua',file='empty.lua',rows={{number=1,text='',highlight=false}}},window.view())
  end)
  it('opens the whole file with exact numbered CRLF rows and one highlighted target',function()
    local window=Window.new(nil,{source=Source,root='C:/project',
      is_file=function(p) return p=='C:/project/src/book.ts' end,
      read=function() return 'const x = 1;\r\nexport function pick() {}\r\n' end})
    assert.is_true(window.open({lang='typescript',file='src\\book.ts',name='pick'}))
    assert.same({title='C:/project/src/book.ts:2',file='C:/project/src/book.ts',line=2,rows={
      {number=1,text='const x = 1;',highlight=false},
      {number=2,text='export function pick() {}',highlight=true},
      {number=3,text='',highlight=false}}},window.view())
  end)
end)
