local E=require('uml.edn')
local G=require('uml.domain.geom')
local g=G.get
local function read(path) local f=assert(io.open(path,'rb')); local text=f:read('*a'); f:close(); return E.parse(text) end
local function write(path,text) local f=assert(io.open(path,'wb')); f:write(text); f:close() end
describe('viewer mailbox files and user events',function()
  it('atomically pops FIFO mail before handling, retains next-id and ignores the saved cursor',function()
    local path=os.tmpname()
    write(path,'{:next-id 8 :queue [{:id 2 :op :context :context :real} {:id 7 :op :display :path "a.edn"} {:id 5 :op :quit-for-restart}]}')
    local mailbox=require('uml.adapters.mailbox').open(path)
    local cmd=mailbox.take(2)
    assert.are.equal('display',G.name(g(cmd,'op')))
    assert.is_true(E.equal(E.parse('{:next-id 8 :queue [{:id 5 :op :quit-for-restart}]}'),read(path)))
    assert.are.equal('quit-for-restart',G.name(g(mailbox.take(2),'op')))
    assert.is_nil(mailbox.take(2)); assert.are.equal(8,g(read(path),'next-id'))
    os.remove(path)
  end)
  it('emits exact legacy element menu labels and durable target/context mail',function()
    local Menu=require('uml.adapters.mail_menu'); local Mail=require('uml.adapters.mail')
    local path=os.tmpname(); write(path,'{:next-id 1 :queue []}')
    local mailbox=require('uml.adapters.mailbox').open(path)
    local s={scene=E.parse('{:classes [{:id :c :ns "app.c" :contents [{:id :child}]}]}'),extra=E.parse('{:proposal-id :p}')}
    local selection=E.parse('{:kind :class :id :c}')
    local labels={}; for _,entry in ipairs(Menu.entries()) do labels[#labels+1]=entry.label end
    assert.are.same({'Refresh CRAP','Refresh Mutation','Refresh All Mutation','Omit'},labels)
    local mail=Mail.new('unused',{outbox=mailbox})
    for _,entry in ipairs(Menu.entries()) do mail.menu_action(s,selection,entry.op) end
    local expected=E.parse('{:next-id 5 :queue [{:id 1 :op :refresh-crap :target {:id :c :kind :component :ns "app.c" :proposal-id :p}} {:id 2 :op :refresh-mutate :target {:id :c :kind :component :ns "app.c" :proposal-id :p}} {:id 3 :op :refresh-mutate-all :target {:id :c :kind :component :ns "app.c" :proposal-id :p}} {:id 4 :op :omit :target {:id :c :kind :component :ns "app.c" :proposal-id :p}}]}')
    assert.is_true(E.equal(expected,read(path)))
    s=mail.send_context(s,E.parse('{:context :real}'))
    assert.is_true(E.equal(E.parse('{:context :real}'),s.discussion_context))
    assert.is_true(E.equal(E.parse('{:id 5 :op :context :context :real}'),g(read(path),'queue')[5]))
    os.remove(path)
  end)
  it('returns P to the namespace tree without changing discussion context',function()
    local D=require('uml.application.document'); local Events=require('uml.application.events')
    local s=D.new(read('fixtures/jvm-goldens/lua.ir.edn'),1)
    s.extra=E.parse('{:proposal-id :p :proposal true :open-layer :layer}')
    s.discussion_context=E.parse('{:context :proposal :proposal-id :p}')
    local n=Events.on_key(s,'p')
    assert.is_nil(g(n.extra,'proposal-id')); assert.is_nil(g(n.extra,'open-layer')); assert.are.equal(0,#n.focus)
    assert.is_true(E.equal(s.discussion_context,n.discussion_context))
  end)
  it('keeps context through display until next context and drains mail after quit',function()
    local D=require('uml.application.document'); local IR=require('uml.domain.ir')
    local s=D.new(IR.read_document('{:packages [{:label "P" :classes [{:id :a}]}]}'),1)
    s.path='root/a.edn'; s.project_root='root'; s.cam_x=75; s.zoom=2
    local boundary={resolve=function(p,root) return root..'/'..p end,canonical=function(p) return p:gsub('/%./','/') end,
      load=function(p) local n=D.new(s.document,2); n.path=p; return n end}
    s=D.apply_mail(s,E.parse('{:id 1 :op :context :context :proposal :proposal-id :p :name "中文" :ignored true}'),boundary)
    s=D.apply_mail(s,E.parse('{:id 2 :op :display :path "./a.edn"}'),boundary)
    assert.are.equal(75,s.cam_x); assert.are.equal(2,s.zoom)
    assert.is_true(E.equal(E.parse('{:context :proposal :proposal-id :p :name "中文"}'),s.discussion_context))
    s=D.apply_mail(s,E.parse('{:id 3 :op :display :path "b.edn"}'),boundary)
    assert.are.equal(0,s.cam_x); assert.are.equal(1,s.zoom)
    local queued={E.parse('{:id 4 :op :quit-for-restart}'),E.parse('{:id 5 :op :context :context :real}')}
    s=D.poll_mail(s,{take=function() return table.remove(queued,1) end},boundary)
    assert.is_true(s.quit_for_restart); assert.are.equal(5,s.mail_seen)
    assert.is_true(E.equal(E.parse('{:context :real}'),s.discussion_context))
  end)
end)
