local E=require('uml.edn')
local G=require('uml.domain.geom')
local lfs=require('lfs')

local function get(m,k) return G.get(m,k) end

local function temp_dir()
  local dir=os.tmpname(); os.remove(dir)
  assert(lfs.mkdir(dir))
  return dir
end

local function cleanup(dir)
  for name in lfs.dir(dir) do
    if name~='.' and name~='..' then os.remove(dir..'/'..name) end
  end
  lfs.rmdir(dir)
end

describe('sibling policy discovery',function()
  it('finds a sibling policy file only when that file exists',function()
    local PolicyFile=require('uml.adapters.policy_file')
    local dir=temp_dir()
    local edn=dir..'/diagram.edn'
    local policy=dir..'/diagram.policy.edn'
    local f=assert(io.open(policy,'wb')); f:write('{:title "T"}'); f:close()
    local ok,message=pcall(function()
      assert.is_nil(PolicyFile.path_for(nil))
      assert.is_nil(PolicyFile.path_for(dir..'/notes.txt'))
      assert.is_nil(PolicyFile.path_for(dir..'/missing.edn'))
      assert.equals(policy,PolicyFile.path_for(edn))
    end)
    cleanup(dir)
    assert.is_true(ok,message)
  end)
end)

describe('proposal transitions',function()
  local function proposal_named(doc,name)
    for _,p in ipairs(G.get(doc,'proposals') or {}) do if G.get(p,'name')==name then return p end end
  end
  it('adds, renames, and deletes a proposal without touching the IR path',function()
    local D=require('uml.application.document')
    local Events=require('uml.application.events')
    local doc=E.parse('{:hierarchical true :title "T" :classes [] :edges [] :order [] :proposals [{:id :old :name "Old" :layers []}]}')
    local s=D.new(doc,'one'); s.path=nil
    local forbidden={exists=function() error('no filesystem reads') end,
      read=function() error('no filesystem reads') end,
      write=function() error('no filesystem writes') end}
    local added=Events.add_proposal(s,{now=1700000000,boundary=forbidden})
    local id=G.get(added.extra,'proposal-id')
    assert.is_not_nil(id)
    assert.is_true(G.get(added.extra,'proposal'))
    assert.equals(2,#G.get(added.document,'proposals'))
    assert.is_not_nil(G.get(added.document,'proposals')[2])
    assert.matches('^%d%d%d%d%-%d%d%-%d%d %d%d:%d%d:%d%d$',G.get(G.get(added.document,'proposals')[2],'name'))
    assert.equals(G.name(id),G.get(G.get(added.document,'proposals')[2],'id').name)
    local renamed=Events.rename_proposal(added,id,'Named')
    assert.is_not_nil(proposal_named(renamed.document,'Named'))
    assert.equals(2,#G.get(renamed.document,'proposals'))
    local gone=Events.delete_proposal(renamed,id)
    assert.is_nil(G.get(gone.extra,'proposal-id'))
    assert.is_false(G.get(gone.extra,'proposal'))
    assert.equals(1,#G.get(gone.document,'proposals'))
    assert.equals('Old',G.get(G.get(gone.document,'proposals')[1],'name'))
    assert.are.equal(s,Events.rename_proposal(s,id,'   '))
    assert.are.equal(s,Events.delete_proposal(s,nil))
  end)
  it('persists add, rename, and delete through the sibling policy boundary',function()
    local D=require('uml.application.document')
    local Events=require('uml.application.events')
    local PolicyFile=require('uml.adapters.policy_file')
    local dir=temp_dir()
    local edn=dir..'/diagram.edn'
    local policy=dir..'/diagram.policy.edn'
    local f=assert(io.open(policy,'wb')); f:write('{:title "Keep" :proposals [{:id :old :name "Old" :layers []}]}'); f:close()
    local doc=E.parse('{:hierarchical true :title "T" :classes [] :edges [] :order [] :proposals [{:id :old :name "Old" :layers []}]}')
    local s=D.new(doc,'one'); s.path=edn
    local ok,message=pcall(function()
      local added=Events.add_proposal(s,{now=1700000000,boundary=PolicyFile})
      assert.is_true(PolicyFile.exists(edn))
      assert.matches('^;; Generated',PolicyFile.read(edn))
      local ir=E.parse(PolicyFile.read(edn))
      assert.equals(2,#G.get(ir,'proposals'))
      local pol=E.parse(PolicyFile.read(policy))
      assert.equals(2,#G.get(pol,'proposals'))
      assert.equals('Keep',G.get(pol,'title'))
      local id=G.get(added.extra,'proposal-id')
      local renamed=Events.rename_proposal(added,id,'Named',{boundary=PolicyFile})
      assert.is_not_nil(proposal_named(E.parse(PolicyFile.read(policy)),'Named'))
      local gone=Events.delete_proposal(renamed,id,{boundary=PolicyFile})
      assert.equals(1,#G.get(E.parse(PolicyFile.read(policy)),'proposals'))
      assert.equals(1,#G.get(E.parse(PolicyFile.read(edn)),'proposals'))
      assert.is_false(PolicyFile.exists(dir..'/other.policy.edn'))
      assert.is_not_nil(gone)
    end)
    cleanup(dir)
    assert.is_true(ok,message)
  end)
  it('preserves omissions and authored grouping state through CRUD, persistence and reload',function()
    local D=require('uml.application.document')
    local Events=require('uml.application.events')
    local PolicyFile=require('uml.adapters.policy_file')
    local dir=temp_dir(); local path=dir..'/diagram.edn'; local policy=dir..'/diagram.policy.edn'
    local proposal='{:id :kept :name "Named" :layers [{:id :group :nses [:app] :layout [:c :a]}] :omit [:app.hidden :app.other] :layout {:order [:b :a]} :notice "derived" :proposal true}'
    local doc=E.parse('{:hierarchical true :title "T" :classes [] :edges [] :order [] :proposals ['..proposal..']}')
    local original=E.parse('{:title "Keep" :lang :lua :omit [:global.hidden] :custom {:order [:z :a]} :proposals ['..proposal..']}')
    local file=assert(io.open(policy,'wb')); file:write(E.encode(original)); file:close()
    local ok,message=pcall(function()
      local state=D.new(doc,'one'); state.path=path
      local function check(s,stamp)
        local reloaded,changed,err=D.reload(s,PolicyFile.read(path),stamp)
        assert.is_nil(err); assert.is_true(changed)
        local persisted=E.parse(PolicyFile.read(policy))
        for _,record in ipairs{G.get(reloaded.document,'proposals')[1],G.get(persisted,'proposals')[1]} do
          assert.is_true(E.equal(E.parse('[:app.hidden :app.other]'),G.get(record,'omit')))
          assert.is_true(E.equal(E.parse('{:order [:b :a]}'),G.get(record,'layout')))
          assert.is_true(E.equal(E.parse('[:c :a]'),G.get(G.get(record,'layers')[1],'layout')))
          assert.is_nil(G.get(record,'notice')); assert.is_nil(G.get(record,'proposal'))
        end
        for _,key in ipairs{'title','lang','omit','custom'} do assert.is_true(E.equal(G.get(original,key),G.get(persisted,key))) end
        return reloaded
      end
      state=check(Events.add_proposal(state,{now=1700000000,boundary=PolicyFile}),'two')
      local added=G.get(state.extra,'proposal-id')
      state=check(Events.rename_proposal(state,E.keyword('kept'),'Renamed',{boundary=PolicyFile}),'three')
      assert.equals('Renamed',G.get(G.get(state.document,'proposals')[1],'name'))
      state=check(Events.delete_proposal(state,added,{boundary=PolicyFile}),'four')
      assert.equals(1,#G.get(state.document,'proposals'))
      check(D.new(D.write_proposals(path,state.document,PolicyFile),'zero'),'five')
    end)
    cleanup(dir); assert.is_true(ok,message)
  end)
  it('renames, deletes, or ignores a proposal op',function()
    local Events=require('uml.application.events')
    assert.is_nil(Events.rename_op(E.keyword('ccp'),nil))
    assert.is_nil(Events.rename_op(E.keyword('ccp'),''))
    assert.is_nil(Events.rename_op(E.keyword('ccp'),'   '))
    local op=Events.rename_op(E.keyword('ccp'),'  New  ')
    assert.equals('rename',G.name(G.get(op,'op')))
    assert.equals('New',G.get(op,'name'))
    local D=require('uml.application.document')
    local doc=E.parse('{:hierarchical true :title "T" :classes [] :edges [] :order [] :proposals [{:id :a :name "A" :layers []}]}')
    local s=D.new(doc,'one'); s.path=nil
    local renamed=Events.apply_proposal_op(s,Events.rename_op(E.keyword('a'),'  New  '))
    assert.equals('New',G.get(G.get(renamed.document,'proposals')[1],'name'))
    local deleted=Events.apply_proposal_op(renamed,E.parse('{:op :delete :id :a}'))
    assert.equals(0,#G.get(deleted.document,'proposals'))
    assert.are.equal(s,Events.apply_proposal_op(s,E.parse('{:op :nope}')))
  end)
end)

describe('inspector hit-testing and actions',function()
  local function state()
    local D=require('uml.application.document')
    local doc=E.parse('{:hierarchical true :title "T" :classes [{:id :leaf}] :edges [] :order [] :proposals [{:id :a :name "A" :layers []} {:id :b :name "B" :layers []}]}')
    local s=D.new(doc,'one'); s.path=nil; return s
  end
  it('hits the real diagram, proposal rows, New Proposal, and Declutter',function()
    local I=require('uml.application.inspector')
    local s=state(); local w=1500
    local real=I.real_diagram_rect(w); local row=I.proposal_row_rect(w,0)
    local nr=I.new_proposal_rect(w,2); local dr=I.declutter_rect(w,2)
    local function hit(x,y) return I.hit(s,x,y,w) end
    assert.equals('real-diagram',G.name(G.get(hit(G.cx(real),G.cy(real)),'kind')))
    assert.is_true(G.bottom(real)<I.proposals_label_y)
    assert.is_true(I.proposals_label_y<G.get(row,'y'))
    local row_hit=hit(G.get(row,'x')+2,G.get(row,'y')+2)
    assert.equals('proposal',G.name(G.get(row_hit,'kind')))
    assert.equals('a',G.name(G.get(row_hit,'id')))
    assert.equals(0,G.get(row_hit,'index'))
    assert.equals('new-proposal',G.name(G.get(hit(G.cx(nr),G.cy(nr)),'kind')))
    assert.equals('declutter',G.name(G.get(hit(G.cx(dr),G.cy(dr)),'kind')))
    assert.is_nil(hit(10,10))
  end)
  it('switches proposal, adds one, cycles declutter, or ignores the hit',function()
    local I=require('uml.application.inspector')
    local s=state(); s.focus=E.parse('[:x]'); E.assoc(s.extra,E.keyword('open-layer'),E.keyword('z'))
    E.assoc(s.extra,E.keyword('proposal'),true); E.assoc(s.extra,E.keyword('proposal-id'),E.keyword('a'))
    local shown=I.press(s,E.parse('{:kind :proposal :id :a}'))
    assert.equals('a',G.name(G.get(shown.extra,'proposal-id')))
    assert.is_true(G.get(shown.extra,'proposal'))
    assert.equals(0,#shown.focus)
    assert.is_nil(G.get(shown.extra,'open-layer'))
    local added=I.press(s,E.parse('{:kind :new-proposal}'),{now=1700000000})
    assert.is_not_nil(G.get(added.extra,'proposal-id'))
    assert.equals(3,#G.get(added.document,'proposals'))
    local cycle=require('uml.application.document').new(E.parse('{:hierarchical true :title "T" :classes [] :edges [] :order []}'),'one')
    E.assoc(cycle.extra,E.keyword('declutter'),E.keyword('full'))
    local cleared=I.press(cycle,E.parse('{:kind :declutter}'))
    assert.equals('arrows',G.name(G.get(cleared.extra,'declutter')))
    assert.are.equal(s,I.press(s,E.parse('{:kind :nope}')))
    assert.are.equal(s,I.press(s,nil))
  end)
  it('hits the inspector Regen control',function()
    local I=require('uml.application.inspector')
    assert.is_true(I.regen_hit(1300,880,1500,920))
    assert.is_false(I.regen_hit(100,100,1500,920))
  end)
  it('anchors the proposal menu at the pointer and renames or deletes',function()
    local I=require('uml.application.inspector')
    local s=state()
    local menu=I.menu(s,E.keyword('a'),{x=12,y=34})
    assert.equals('a',G.name(G.get(menu,'id')))
    assert.equals('A',G.get(menu,'name'))
    assert.are.same({x=12,y=34},{x=G.get(G.get(menu,'anchor'),'x'),y=G.get(G.get(menu,'anchor'),'y')})
    local entries=G.get(menu,'entries')
    assert.equals('Rename',G.get(entries[1],'label'))
    assert.equals('rename',G.name(G.get(entries[1],'op')))
    assert.equals('Delete',G.get(entries[2],'label'))
    assert.equals('delete',G.name(G.get(entries[2],'op')))
    local renamed=I.menu_action(s,E.keyword('rename'),E.keyword('a'),'  New  ')
    assert.equals('New',G.get(G.get(renamed.document,'proposals')[1],'name'))
    local deleted=I.menu_action(renamed,E.keyword('delete'),E.keyword('a'))
    assert.equals(1,#G.get(deleted.document,'proposals'))
    assert.are.equal(s,I.menu_action(s,E.keyword('nope'),E.keyword('a'),'X'))
    assert.are.equal(s,I.menu_action(s,E.keyword('rename'),E.keyword('a'),'   '))
    assert.is_nil(I.menu(s,E.keyword('missing'),{x=1,y=2}))
  end)
  it('routes right-clicks to an element menu only for classes, children, and proposal packages',function()
    local Events=require('uml.application.events')
    assert.is_true(Events.element_menu(E.parse('{:kind :class :id :a}')))
    assert.is_true(Events.element_menu(E.parse('{:kind :child :id :a.b :parent :a}')))
    assert.is_true(Events.element_menu(E.parse('{:kind :package :id :proposal.ccp}')))
    assert.is_false(Events.element_menu(E.parse('{:kind :package :id :p}')))
    assert.is_false(Events.element_menu(nil))
  end)
end)

describe('proposal persistence',function()
  local function write_file(path,text)
    local f=assert(io.open(path,'wb')); f:write(text); f:close()
  end
  local function read_file(path)
    local f=assert(io.open(path,'rb')); local text=f:read('*a'); f:close(); return text
  end
  local function same(expected,actual)
    assert.is_true(E.equal(E.parse(expected),actual),E.encode(actual))
  end
  it('writes proposals to the IR and the policy file',function()
    local D=require('uml.application.document')
    local PolicyFile=require('uml.adapters.policy_file')
    local dir=temp_dir()
    local edn=dir..'/diagram.edn'
    local policy=dir..'/diagram.policy.edn'
    local explicit=dir..'/explicit.policy.edn'
    local doc=E.parse('{:title "T" :proposal {:name "old" :layers []} :proposals [{:id :one :name "One" :layers []} {:id :two :name "Two" :layers [{:id :kernel :label "Kernel" :nses [:domain]}]}]}')
    write_file(policy,'{:title "Keep" :proposal {:name "old"}}')
    write_file(explicit,'{:title "Keep" :proposal {:name "old"}}')
    local ok,message=pcall(function()
      local out=D.write_proposals(edn,doc,PolicyFile)
      local written=E.parse(read_file(edn))
      local pol=E.parse(read_file(policy))
      assert.equals(2,#get(out,'proposals'))
      assert.equals('one',G.name(get(get(out,'proposals')[1],'id')))
      assert.equals('Two',get(get(out,'proposals')[2],'name'))
      assert.is_true(E.equal(get(out,'proposals'),get(written,'proposals')))
      assert.is_true(E.equal(get(out,'proposals'),get(pol,'proposals')))
      assert.is_nil(get(pol,'proposal'))
      assert.equals('Keep',get(pol,'title'))
      assert.is_not_nil(get(out,'proposal'))

      local explicit_doc=E.parse('{:title "T" :policy-file "'..explicit:gsub('\\','/')..'" :proposals [{:id :one :name "One" :layers []}]}')
      local by_file=D.write_proposals(nil,explicit_doc,PolicyFile)
      local pol2=E.parse(read_file(explicit))
      assert.is_true(E.equal(get(by_file,'proposals'),get(pol2,'proposals')))
      assert.is_nil(get(pol2,'proposal'))

      local only=dir..'/only.edn'
      local skipped=D.write_proposals(only,E.parse('{:title "T" :policy-file "'..(dir..'/nope.policy.edn'):gsub('\\','/')..'" :proposals [{:id :one :name "One" :layers []}]}'),PolicyFile)
      assert.is_true(get(skipped,'proposals')~=nil)
      assert.equals(1,#get(skipped,'proposals'))
      assert.is_true(PolicyFile.exists(only))
      assert.is_false(PolicyFile.exists(dir..'/nope.policy.edn'))
    end)
    cleanup(dir)
    assert.is_true(ok,message)
  end)
end)

