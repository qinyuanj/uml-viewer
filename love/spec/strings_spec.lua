local E=require('uml.edn')
local D=require('uml.application.document')
local IR=require('uml.domain.ir')
local function rows_text(rows) local t={}; for _,r in ipairs(rows) do t[#t+1]=r.text end; return t end
local function has(list,value) for _,v in ipairs(list) do if v==value then return true end end; return false end
describe('Chinese UI string table',function()
  it('uses the glossary terms and keeps metric and tool names English',function()
    local S=require('uml.application.strings')
    assert.are.equal('源码图',S.real_diagram)
    assert.are.equal('检查器',S.inspector)
    assert.are.equal('精简视图',S.declutter)
    assert.are.equal('新建提案',S.new_proposal)
    assert.is_truthy(S.tree_and_proposals:find('命名空间',1,true)); assert.is_truthy(S.tree_and_proposals:find('提案',1,true))
    assert.are.equal('< 返回',S.back)
    assert.are.same({'Crap','CC','Cov','killed','survived','uncovered'},{S.columns.crap,S.columns.cc,S.columns.cov,S.columns.killed,S.columns.survived,S.columns.uncovered})
    assert.are.equal('行覆盖率',S.column_tips.cov)
    for _,k in ipairs{'crap','cc','killed','survived','uncovered'} do assert.is_truthy(S.column_tips[k]:find('[\228-\233]')) end
  end)
  it('feeds every table character to the font atlas text',function()
    local S=require('uml.application.strings')
    local glyphs=S.glyph_text()
    for _,needle in ipairs{'源码图','提案','隐藏','命名空间','类','精简视图','检查器','返回','行覆盖率','刷新','全量','μ','σ','α','«','»','←','—','：'} do
      assert.is_truthy(glyphs:find(needle,1,true),'missing glyph text '..needle)
    end
  end)
  it('labels the element menu in Chinese while mail operations stay English',function()
    local Menu=require('uml.adapters.mail_menu')
    local labels,ops={},{}; for _,e in ipairs(Menu.entries()) do labels[#labels+1]=e.label; ops[#ops+1]=e.op end
    assert.are.same({'刷新 CRAP','刷新 mutation','全量 mutation','隐藏'},labels)
    assert.are.same({'refresh-crap','refresh-mutate','refresh-mutate-all','omit'},ops)
  end)
  it('names the real diagram 源码图 unless the document has a title, and helps in Chinese with English key names',function()
    local I=require('uml.application.inspector')
    local state=D.new(IR.read_document('{:hierarchical true :prefix "demo" :classes [{:id :a :ns "demo.a"}] :proposals [{:id :plan :name "中文方案" :layers []}]}'))
    assert.are.equal('源码图',I.commands(state)[1].label)
    local titled=D.new(IR.read_document('{:title "Tiny" :hierarchical true :prefix "demo" :classes [{:id :a :ns "demo.a"}]}'))
    assert.are.equal('Tiny',I.commands(titled)[1].label)
    local help=I.empty_explanation(state)
    for _,needle in ipairs{'单击','双击','Esc','Shift','Ctrl+0','R ','源码图','提案'} do assert.is_truthy(help:find(needle,1,true),'help lacks '..needle) end
    local menu=I.menu(state,E.keyword('plan'))
    local G=require('uml.domain.geom'); local entries=G.get(menu,'entries')
    assert.are.equal('重命名',G.get(entries[1],'label')); assert.are.equal('删除',G.get(entries[2],'label'))
    assert.are.equal('rename',G.name(G.get(entries[1],'op'))); assert.are.equal('delete',G.name(G.get(entries[2],'op')))
  end)
  it('writes the class card in Chinese around English metric names',function()
    local Detail=require('uml.application.detail')
    local rows=Detail.rows({class={name='D',level=2,crap={mu=14.2,max=134.6,sigma=34.9},killed=0,survived=0,uncovered=0,sites=0,fields={{text='n'}},ops={{name='go',text='go()'}}},rels={{id=E.keyword('b'),phrase='依赖',name='B',label='db'}}})
    local text=rows_text(rows)
    assert.is_true(has(text,'层级 2')); assert.is_true(has(text,'包  ')); assert.is_true(has(text,'字段')); assert.is_true(has(text,'关系')); assert.is_true(has(text,'依赖  B  «db»'))
    assert.is_true(has(text,'Crap μ 14.2 max 134.6 σ 34.9'))
    local go; for _,r in ipairs(rows) do if r['op-name']=='go' then go=r end end
    assert.are.equal('---无 mutation 位点---',go['mut-note'])
    for _,case in ipairs{{'inheritance','继承','被继承'},{'implements','实现','被实现'},{'association','关联','被关联'},{'dependency','依赖','被依赖'},{'aggregation','聚合','被聚合'},{'composition','组合','被组合'},{'other','指向','来自'}} do
      local s=E.parse('{:classes [{:id :a :name "A"} {:id :b :name "B"}] :edges [{:from :a :to :b :kind :'..case[1]..'}]}')
      assert.are.equal(case[2],Detail.model(s,E.keyword('a')).rels[1].phrase); assert.are.equal(case[3],Detail.model(s,E.keyword('b')).rels[1].phrase)
    end
  end)
end)
