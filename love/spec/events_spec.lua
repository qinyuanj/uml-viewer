local E=require('uml.edn')
local G=require('uml.domain.geom')
local D=require('uml.application.document')
local Events=require('uml.application.events')
local g,k=G.get,E.keyword
local function state()
  return D.new(E.parse('{:hierarchical true :title "Tree" :classes [{:id :source} {:id :source.lua} {:id :source.lua.parser} {:id :other}] :edges []}'),'one')
end
local function ids(s) local out={}; for _,c in ipairs(g(s.scene,'classes')) do out[#out+1]=G.name(g(c,'id')) end; return out end
describe('viewer application event sequences',function()
  it('enters nested namespaces and returns with back, escape and the back hotspot',function()
    local s=state(); s.cam_x=10; s.cam_y=20; s.zoom=2; s.selected=k('old'); s.discussion_context={context='proposal',name='Independent'}
    local a=Events.drill(s,k('source')); local b=Events.drill(a,k('source.lua'))
    assert.are.same({'source.lua','source.lua.parser'},ids(b))
    assert.is_true(E.equal(E.parse('[:source :lua]'),b.focus))
    assert.are.equal(0,b.cam_x); assert.are.equal(0,b.cam_y); assert.are.equal(2,b.zoom); assert.is_nil(b.selected)
    assert.are.equal(s.discussion_context,b.discussion_context)
    assert.is_true(E.equal(a.focus,Events.on_key(b,'escape').focus))
    assert.is_true(E.equal(E.vector(),Events.on_press(a,20,20).focus))
    assert.are.equal(s,Events.back(s)); assert.are.equal(10,s.cam_x)
  end)
  it('pans within scene bounds including negative origins and a reduced canvas',function()
    local s=state(); s.scene=G.map{size=G.map{w=1400,h=4000,['min-x']=-400,['min-y']=-50}}
    local dims={window_w=1500,window_h=800,view_w=1220}
    local a=Events.on_scroll(s,100,{horizontal=true,window_w=1500,window_h=800,view_w=1220})
    assert.are.equal(180,a.cam_x)
    assert.are.equal(-400,Events.on_scroll(a,-100,{horizontal=true,view_w=1220}).cam_x)
    assert.are.equal(96,Events.on_key(s,'down',dims).cam_y)
    assert.are.equal(-50,Events.on_scroll(s,-100,dims).cam_y)
    assert.are.equal(0,Events.on_scroll(s,{},dims).cam_y)
    assert.are.equal(96,Events.on_scroll(s,{count=2},dims).cam_y)
  end)
  it('zooms around the canvas center, normalizes keys, clamps and resets',function()
    local s=state(); local dims={control=true,window_w=1500,view_w=1220,window_h=900}
    local a=Events.on_key(s,'+',dims)
    assert.are.equal(1.1,a.zoom)
    local x,y=Events.world_xy(a,610,450); assert.are.equal(610,x); assert.are.equal(450,y)
    local b=Events.on_key(a,'unknown',{control=true,key_code=45,view_w=1220,window_h=900})
    assert.are.equal(1,b.zoom); assert.are.equal(0,b.cam_x)
    assert.are.equal(1,Events.on_key(a,'0',dims).zoom)
    assert.are.equal(s,Events.on_key(s,'+',{}))
    assert.are.equal('out',Events.zoom_dir('unknown',{raw_key=string.char(31)}))
    for i=1,100 do a=Events.on_key(a,'=',dims) end; assert.are.equal(10,a.zoom)
    for i=1,100 do a=Events.on_key(a,'minus',dims) end; assert.are.equal(.1,a.zoom)
    s.zoom=2; s.cam_x=10; s.cam_y=20; assert.are.same({15,30},{Events.world_xy(s,10,20)})
  end)
  it('hits, hovers and selects with world coordinates without changing a detail card',function()
    local s=state(); s.zoom=2; s.cam_x=10; s.cam_y=20; s.detail_id=k('kept')
    local c=require('uml.engine.hit').class_by_id(s.scene,k('source')); local r=g(c,'rect'); local x=(g(r,'x')+5-10)*2; local y=(g(r,'y')+5-20)*2
    local moved=Events.on_move(s,x,y); local pressed=Events.on_press(moved,x,y)
    assert.is_true(E.equal(g(c,'id'),g(pressed.selected,'id')))
    assert.is_true(E.equal(moved.hover,pressed.selected)); assert.are.same({x,y},moved.pointer)
    assert.is_nil(Events.on_press(pressed,-10000,-10000).selected)
    assert.are.equal(s.detail_id,Events.on_key(pressed,'escape').detail_id)
    assert.is_true(E.equal(g(c,'id'),Events.layer_id(pressed.selected)))
    assert.is_nil(Events.layer_id(G.map{kind=k('class'),id=k('leaf')}))
    assert.is_true(E.equal(k('source'),Events.layer_id(E.parse('{:kind :child :id :source.lua :parent :source}'))))
    assert.are.equal(s,Events.on_key(s,'x'))
    s.waiting=true; s.metrics_stamp='old'; local reload=Events.on_key(s,'r'); assert.are.equal(0,reload.mtime); assert.is_nil(reload.metrics_stamp); assert.is_nil(reload.waiting)
  end)
  it('opens existing proposal packages and nested groups, then returns without inventing proposals',function()
    local doc=E.parse('{:hierarchical true :classes [{:id :source.lua} {:id :other}] :edges [] :proposals [{:id :split :name "Split" :layers [{:id :core :label "Core" :nses [{:id :parser :label "Parser" :nses [:source.lua]}]}]}]}')
    local s=D.new(doc,'one'); s.discussion_context={context='real'}
    local p=Events.show_proposal(s,k('split')); assert.is_true(g(p.extra,'proposal'))
    local layer=Events.drill(p,k('proposal.core')); assert.is_true(E.equal(k('proposal.core'),g(layer.extra,'open-layer')))
    local group=Events.drill(p,k('parser')); assert.are.same({'source.lua'},ids(group)); assert.are.equal(0,#group.focus)
    assert.is_nil(g(Events.on_key(group,'esc').extra,'open-layer'))
    assert.is_nil(g(Events.on_press(layer,20,20).extra,'open-layer'))
    local real=Events.show_proposal(group,nil); assert.is_nil(g(real.extra,'proposal-id')); assert.is_false(g(real.extra,'proposal'))
    assert.are.equal(doc,real.document); assert.are.equal(s.discussion_context,real.discussion_context)
    assert.are.equal(s,Events.show_proposal(s,k('absent')))
    assert.are.equal('arrows',G.name(g(Events.cycle_declutter(s).extra,'declutter')))
    assert.are.equal('full',G.name(g(Events.cycle_declutter(Events.cycle_declutter(Events.cycle_declutter(Events.cycle_declutter(Events.cycle_declutter(s))))).extra,'declutter')))
  end)
  it('retains navigation and discussion state across a valid document reload',function()
    local s=Events.drill(state(),k('source')); s=Events.on_key(s,'+',{control=true}); s.discussion_context={context='proposal'}; s.selected=k('selection'); s.detail_id=k('card')
    local n,changed=D.reload(s,E.encode(s.document),'two',nil,'metrics-two')
    assert.is_true(changed); assert.are.equal(s.cam_x,n.cam_x); assert.are.equal(s.zoom,n.zoom)
    assert.are.equal(s.discussion_context,n.discussion_context); assert.are.equal(s.selected,n.selected); assert.are.equal(s.detail_id,n.detail_id)
    assert.is_true(E.equal(s.focus,n.focus)); assert.are.same(ids(s),ids(n))
  end)
  it('compiles explicit proposal options and gives namespace focus priority like the legacy viewer',function()
    local doc=E.parse('{:hierarchical true :classes [{:id :source.lua} {:id :other}] :edges [] :proposals [{:id :split :name "Split" :layers [{:id :core :label "Core" :nses [:source.lua]}]}]}')
    local p=D.compile_view(doc,nil,nil,E.parse('{:proposal-id :split}'))
    assert.is_true(g(g(p,'diagram'),'proposal'))
    local n=D.compile_view(doc,nil,E.parse('[:source]'),E.parse('{:proposal true :proposal-id :split}'))
    assert.is_nil(g(g(n,'diagram'),'proposal'))
    assert.are.equal('source',g(g(n,'diagram'),'title'))
  end)
  it('ignores numeric and absent keys and accepts tagged keyword aliases',function()
    local s=state(); assert.is_nil(Events.zoom_dir(45,{})); assert.is_nil(Events.zoom_dir(nil,{}))
    assert.are.equal(s,Events.on_key(s,45)); assert.are.equal(s,Events.on_key(s,nil))
    assert.are.equal('out',Events.zoom_dir(k('minus'),{}))
    assert.are.equal('in',Events.zoom_dir('+',{}))
    assert.are.equal('reset',Events.zoom_dir('0',{}))
  end)
end)
