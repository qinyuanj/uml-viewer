//! IR generation (#136): policy + source tree in, IR out, no window.
//!
//! Port of `love/uml/main/ir_generator.lua` (the CLI) and
//! `love/uml/application/ir_generator.lua` (orchestration). The only public
//! entry is [`run`], the binary's `ir` role.

