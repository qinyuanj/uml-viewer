use std::ffi::OsString;
use std::process::ExitCode;

use edn::Value;

use edn::record::{put, seq};
use files::Adapter;
use value::get_truthy as get;

/// The emit framing from `application/ir_generator.lua`: header, one-line
/// EDN, trailing newline.
fn emit(doc: &Value) -> Result<String, String> {
    Ok(format!(
        ";; Generated by uml ir from the policy file. Do not edit.\n{}\n",
        edn::encode(doc).map_err(|e| e.to_string())?
    ))
}

/// Keys only a generated IR document carries; a policy never declares them.
const IR_ONLY_KEYS: [&str; 3] = ["classes", "edges", "policy-file"];

const USAGE: &str = "usage: ir [policy [output]] [--root directory]";

/// Refuses EDN that is not a policy (#166): a non-map, or a generated IR
/// document passed by mistake (any IR-only key). Source declarations stay
/// optional; `:src` defaults and the language is detected.
fn check_policy_shape(path: &str, policy: &Value) -> Result<(), String> {
    if !matches!(policy, Value::Map(_)) {
        return Err(format!("{path}: policy must be an EDN map; {USAGE}"));
    }
    let ir_keys: Vec<String> = IR_ONLY_KEYS
        .iter()
        .filter(|k| edn::record::get(policy, k).is_some())
        .map(|k| format!(":{k}"))
        .collect();
    if !ir_keys.is_empty() {
        return Err(format!(
            "{path}: is a generated IR document, not a policy (IR-only keys {}); {USAGE}",
            ir_keys.join(" ")
        ));
    }
    Ok(())
}

/// Reads a policy and checks its shape before any detection, scan or write.
fn read_policy(path: &str, adapter: &Adapter) -> Result<Value, String> {
    let text = adapter.read(path)?;
    let text = String::from_utf8(text).map_err(|_| format!("{path}: policy is not UTF-8"))?;
    let policy = edn::parse(&text).map_err(|e| format!("{path}: {e}"))?;
    check_policy_shape(path, &policy)?;
    Ok(policy)
}

/// `scan_policy(nil, p, filenames)`: the CLI always scans fresh (`impl` is
/// nil), so `Detection.select` always runs — validating explicit declarations
/// and detecting from filename snapshots when nothing is declared.
fn scan_policy(p: &Value, filenames: &[String], adapter: &Adapter) -> Result<Value, String> {
    let selected = detection::select(p, filenames)?;
    let sources = seq(get(p, "sources"));
    if !sources.is_empty() {
        let mut scans = Vec::new();
        for s in sources {
            let lang = get(s, "lang")
                .or_else(|| get(p, "lang"))
                .cloned()
                .unwrap_or(Value::Nil);
            let prefix = get(p, "prefix")
                .cloned()
                .unwrap_or(Value::String("uml-viewer".into()));
            let mut opts = Value::Map(vec![(Value::keyword("prefix"), prefix.clone())]);
            let ns_prefix = get(s, "prefix").or_else(|| get(p, "prefix"));
            if let Some(ns_prefix) = ns_prefix {
                opts.assoc(Value::keyword("ns-prefix"), ns_prefix.clone());
            }
            opts.assoc(Value::keyword("lang"), lang.clone());
            let mut exclude: Vec<Value> = Vec::new();
            for xs in [get(p, "exclude"), get(s, "exclude")] {
                for x in seq(xs) {
                    if !exclude.contains(x) {
                        exclude.push(x.clone());
                    }
                }
            }
            if !exclude.is_empty() {
                opts.assoc(Value::keyword("exclude"), Value::Vector(exclude));
            }
            let root = get(s, "root")
                .or_else(|| get(s, "src"))
                .or_else(|| get(p, "src"))
                .cloned()
                .unwrap_or(Value::String("src".into()));
            let root = match &root {
                Value::String(path) => path.clone(),
                _ => return Err(":src must be a string".to_owned()),
            };
            scans.push(graph::scan_project(&lang, &root, &opts, adapter)?);
        }
        return graph::merge_scans(&scans);
    }
    let mut opts = Value::Map(vec![(
        Value::keyword("prefix"),
        get(p, "prefix")
            .cloned()
            .unwrap_or(Value::String("uml-viewer".into())),
    )]);
    let exclude: Vec<Value> = seq(get(p, "exclude")).to_vec();
    if !exclude.is_empty() {
        opts.assoc(Value::keyword("exclude"), Value::Vector(exclude));
    }
    let src = match get(p, "src") {
        Some(Value::String(path)) => path.clone(),
        None => "src".to_owned(),
        _ => return Err(":src must be a string".to_owned()),
    };
    let lang = selected.ok_or_else(|| "no language selected".to_owned())?;
    graph::scan_project(&lang, &src, &opts, adapter)
}

/// `generate(nil, path, out, adapter)`.
fn generate(path: &str, out: Option<String>, adapter: &Adapter) -> Result<String, String> {
    let p = read_policy(path, adapter)?;
    let mut filenames = Vec::new();
    if value::get_truthy(&p, "lang").is_none() && value::get_truthy(&p, "sources").is_none() {
        filenames = adapter.filenames()?;
    }
    let graph = scan_policy(&p, &filenames, adapter)?;
    let extra = policy::unassigned(&p, &graph);
    if !extra.is_empty() {
        let names: Vec<String> = extra
            .iter()
            .map(|c| match get(c, "ns") {
                Some(Value::String(s)) => s.clone(),
                _ => String::new(),
            })
            .collect();
        eprintln!("Unassigned namespaces: {}", names.join(", "));
    }
    let mut doc = policy::apply_policy(&p, &graph);
    put(&mut doc, "policy-file", Value::String(path.to_owned()));
    let out = out
        .or_else(|| {
            get(&p, "out").and_then(|v| match v {
                Value::String(s) => Some(s.clone()),
                _ => None,
            })
        })
        .ok_or_else(|| "output path required".to_owned())?;
    adapter.write(&out, &emit(&doc)?)?;
    Ok(out)
}

fn run_result(args: &[OsString]) -> Result<String, String> {
    let mut root = std::env::current_dir()
        .map_err(|e| e.to_string())?
        .to_string_lossy()
        .into_owned();
    let mut positional: [Option<String>; 2] = [None, None];
    let mut i = 0;
    while i < args.len() {
        let a = args[i].to_str().ok_or("arguments must be UTF-8")?;
        match a {
            "--root" => {
                i += 1;
                root = args
                    .get(i)
                    .and_then(|v| v.to_str())
                    .ok_or("--root requires a path")?
                    .to_owned();
            }
            "--policy" | "--output" => {
                i += 1;
                let value = args
                    .get(i)
                    .and_then(|v| v.to_str())
                    .ok_or_else(|| format!("{a} requires a path"))?;
                let n = if a == "--policy" { 0 } else { 1 };
                if positional[n].is_some() {
                    return Err(format!("duplicate {a}"));
                }
                positional[n] = Some(value.to_owned());
            }
            _ if a.starts_with("--") => return Err(format!("unknown ir option: {a}")),
            _ => {
                let n = if positional[0].is_some() { 1 } else { 0 };
                if positional[n].is_some() {
                    return Err(USAGE.to_owned());
                }
                positional[n] = Some(a.to_owned());
            }
        }
        i += 1;
    }
    if !cfg!(any(target_os = "linux", target_os = "macos")) {
        return Err("IR requires WSL2 or macOS (ADR 0007)".to_owned());
    }
    let adapter = Adapter::new(&root)?;
    let path = positional[0]
        .clone()
        .unwrap_or_else(|| "examples/uml-viewer.policy.edn".into());
    let policy = read_policy(&path, &adapter)?;
    let default_out = value::get_truthy(&policy, "out")
        .and_then(|v| match v {
            Value::String(s) => Some(s.clone()),
            _ => None,
        })
        .unwrap_or_else(|| "diagram.edn".into());
    generate(
        &path,
        Some(positional[1].clone().unwrap_or(default_out)),
        &adapter,
    )
}

/// Runs the `ir` role: `ir [policy [output]] [--root dir] [--policy p] [--output o]`.
pub fn run(args: &[OsString]) -> ExitCode {
    match run_result(args) {
        Ok(out) => {
            println!("Wrote {out}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("IR generation failed: {message}");
            ExitCode::from(1)
        }
    }
}

#[cfg(test)]
mod policy_shape_tests {
    //! #166: the rejection branch of the policy shape check.
    use super::check_policy_shape;

    fn check(text: &str) -> Result<(), String> {
        check_policy_shape("p.edn", &edn::parse(text).unwrap())
    }

    #[test]
    fn each_ir_only_key_marks_a_generated_ir_document() {
        for text in [
            "{:prefix \"app\" :classes []}",
            "{:prefix \"app\" :edges []}",
            "{:prefix \"app\" :policy-file \"policy.edn\"}",
        ] {
            let err = check(text).unwrap_err();
            assert!(err.contains("generated IR document"), "{text}: {err}");
            assert!(
                err.contains("usage: ir [policy [output]] [--root directory]"),
                "{text}: {err}"
            );
        }
    }

    #[test]
    fn the_refusal_names_every_ir_only_key_present() {
        let err = check("{:policy-file \"p\" :classes [] :edges []}").unwrap_err();
        assert!(err.contains(":classes :edges :policy-file"), "{err}");
    }

    #[test]
    fn a_non_map_is_refused_with_the_usage() {
        let err = check("[:classes]").unwrap_err();
        assert!(err.contains("policy must be an EDN map"), "{err}");
        assert!(err.contains("usage: ir [policy [output]]"), "{err}");
    }

    #[test]
    fn policies_with_or_without_a_source_declaration_pass() {
        for text in [
            "{}",
            "{:prefix \"app\"}",
            "{:src \"src\" :prefix \"app\"}",
            "{:lang :rust :sources [{:src \"crates/ir/src\" :prefix \"uml.ir\"}]}",
        ] {
            assert_eq!(Ok(()), check(text), "{text}");
        }
    }
}
