-- Lay out a synthetic IR once with the current Lua scene core and write the
-- renderer-neutral benchmark scene (map #124) as EDN and JSON.
-- Usage: luajit bench/export_scene.lua <in.edn> <out-stem>
-- Writes <out-stem>.scene.edn and <out-stem>.scene.json. Geometry is world
-- units (zoom 1 = 1 view px); colors are RGB 0-255 from domain.theme.
package.path='love/?.lua;'..package.path
local E=require('uml.edn')
local G=require('uml.domain.geom')
local C=require('uml.domain.config')
local T=require('uml.domain.theme')
local IR=require('uml.domain.ir')
local D=require('uml.application.document')
local in_path=assert(arg[1],'input IR'); local stem=assert(arg[2],'output stem')
local g,name=G.get,G.name

local f=assert(io.open(in_path,'rb')); local text=f:read('*a'); f:close()
local started=os.clock()
local scene=D.compile_view(IR.read_document(text))
local compile_s=os.clock()-started

local function r1(x) return math.floor(x*10+.5)/10 end
local function rect(r) return {r1(g(r,'x')),r1(g(r,'y')),r1(g(r,'w')),r1(g(r,'h'))} end
-- Same grading as adapters/class_boxes: missing either metric is worst grade.
local function missing(c) return C.crap_risk(g(c,'crap'))==nil or C.mutation_ratio(c)==nil end
local function grade(c)
  return C.combined_grade(C.crap_grade(C.crap_risk(g(c,'crap'))),C.mutation_grade(C.mutation_ratio(c)))
end
local function bands(c)
  return name(C.crap_band(C.crap_risk(g(c,'crap')))),name(C.mutation_band(C.mutation_ratio(c)))
end

local out={version=1,source=in_path:match('[^/]*$'),packages={},classes={},edges={}}
local size=g(scene,'size')
out.size={w=r1(g(size,'w')),h=r1(g(size,'h')),['min-x']=r1(g(size,'min-x') or 0),['min-y']=r1(g(size,'min-y') or 0)}
for _,p in ipairs(g(scene,'packages')) do
  local gr=grade(p); local cb,mb=bands(p)
  out.packages[#out.packages+1]={id=name(g(p,'id')),label=g(p,'label'),rect=rect(g(p,'rect')),
    grade=r1(gr or 1),fill=T.fill(gr),stroke=T.stroke(gr),['crap-band']=cb,['mutation-band']=mb}
end
local points=0
for _,c in ipairs(g(scene,'classes')) do
  if not g(c,'dummy?') then
    local m=missing(c); local gr=m and C.grade_worst or grade(c); local cb,mb=bands(c)
    local lines={}
    for _,l in ipairs(g(c,'lines') or {}) do
      local t=g(l,'text'); lines[#lines+1]={kind=name(g(l,'kind')),text=t~=E.nil_value and t or nil}
    end
    out.classes[#out.classes+1]={id=name(g(c,'id')),package=name(g(c,'package')),rect=rect(g(c,'rect')),
      shape=name(g(c,'shape')) or 'box',level=g(c,'level'),missing=m,grade=r1(gr),fill=T.fill(gr),stroke=T.stroke(gr),
      ['crap-band']=cb,['mutation-band']=mb,lines=lines}
  end
end
for _,e in ipairs(g(scene,'edges')) do
  local strokes={}
  for _,s in ipairs(g(e,'strokes') or {}) do
    local flat={}; for _,p in ipairs(s) do flat[#flat+1]=r1(p[1]); flat[#flat+1]=r1(p[2]) end
    strokes[#strokes+1]=flat; points=points+#s
  end
  local tip,behind=g(e,'tip'),g(e,'behind')
  out.edges[#out.edges+1]={from=name(g(e,'from')),to=name(g(e,'to')),kind=name(g(e,'kind')),
    violating=g(e,'violating')==true,strokes=strokes,
    tip=tip and {r1(tip[1]),r1(tip[2])} or nil,behind=behind and {r1(behind[1]),r1(behind[2])} or nil}
end

-- Two hand-written encoders over the same plain table: arrays have [1].
local function is_array(t) return t[1]~=nil or next(t)==nil end
local function keys(t) local ks={}; for k in pairs(t) do ks[#ks+1]=k end; table.sort(ks); return ks end
local function num(x) if x==math.floor(x) then return string.format('%d',x) end; return string.format('%.1f',x) end
local function quote(s) return '"'..s:gsub('\\','\\\\'):gsub('"','\\"')..'"' end
local function encode(x,edn,buf)
  local t=type(x)
  if t=='number' then buf[#buf+1]=num(x)
  elseif t=='boolean' then buf[#buf+1]=tostring(x)
  elseif t=='string' then buf[#buf+1]=quote(x)
  elseif is_array(x) then
    buf[#buf+1]='['; for i,v in ipairs(x) do if i>1 then buf[#buf+1]=edn and ' ' or ',' end; encode(v,edn,buf) end; buf[#buf+1]=']'
  else
    buf[#buf+1]='{'
    for i,k in ipairs(keys(x)) do
      if i>1 then buf[#buf+1]=edn and ' ' or ',' end
      buf[#buf+1]=edn and ':'..k..' ' or quote(k)..':'; encode(x[k],edn,buf)
    end
    buf[#buf+1]='}'
  end
end
-- One top-level entry per line keeps diffs and head(1) readable.
local function write(path,edn)
  local buf={}
  buf[#buf+1]=edn and ';; Generated by bench/export_scene.lua. Do not edit.\n{' or '{'
  for i,k in ipairs(keys(out)) do
    if i>1 then buf[#buf+1]=edn and '\n ' or ',\n' end
    buf[#buf+1]=edn and ':'..k..' ' or quote(k)..':'
    local v=out[k]
    if type(v)=='table' and is_array(v) and #v>0 and type(v[1])=='table' then
      buf[#buf+1]='['
      for j,item in ipairs(v) do if j>1 then buf[#buf+1]=edn and '\n  ' or ',\n  ' end; encode(item,edn,buf) end
      buf[#buf+1]=']'
    else encode(v,edn,buf) end
  end
  buf[#buf+1]='}\n'
  local h=assert(io.open(path,'wb')); h:write(table.concat(buf)); h:close()
end
write(stem..'.scene.edn',true); write(stem..'.scene.json',false)
io.stdout:write(string.format('%s: compile %.1fs, %d packages, %d classes, %d edges, %d stroke points, size %.0fx%.0f\n',
  stem,compile_s,#out.packages,#out.classes,#out.edges,points,out.size.w,out.size.h))
